"""The discrete functional and its symmetries (DESIGN.md sections 2, 4 and 5).

F(c; lam) = 1/2 sum_j (e_j - lam) |c_j|^2 + 1/4 int |psi|^4 d(mu),  psi = sum_j c_j f_j,
the slot action's stationary functional in the basis of basis.py (normalized measure on S^3; the overall factor
vol(X) is dropped, which moves no critical point). The nonlinearity is pointwise, |psi(x)|^2 psi(x). The rule of
quadrature.py computes F, its gradient F' (the Galerkin projection of the cubic) and its Hessian F'' exactly.
Real form: x = (Re c, Im c), with the inner product Re(c^H d).

The symmetries act on coefficients: right translation by h acts on each (n, i) block by pi_n(h), with generators
d pi_n(G_a); the phase by e^{i theta}; and on the spinorial slots the quaternionic structure J c = K conj(c), with
K the matrix of psi -> C conj(psi) in the basis (level by level, J^2 = -1), so Sp(1) is generated by i, J and iJ.
"""
import numpy as np
from . import su2, group2i, quadrature, devtools


def to_real(c):
    return np.concatenate([c.real, c.imag])


def to_complex(x):
    m = len(x) // 2
    return x[:m] + 1j * x[m:]


def real_of_linear(T):
    """The real 2m x 2m matrix of the complex-linear map c -> T c."""
    return np.block([[T.real, -T.imag], [T.imag, T.real]])


def real_of_antilinear(K):
    """The real 2m x 2m matrix of the antilinear map c -> K conj(c)."""
    return np.block([[K.real, K.imag], [K.imag, -K.real]])


class Functional:
    """Exact F, F' and F'' through the rule. Each chunk's projection onto the basis is a GEMM, P^H (.): einsum's
    accumulation over a large chunk lost about 1e-13 on the rigid branch (UB; DEVLOG). The basis is evaluated in
    chunks, blocks of alpha rows at one t node, each at most chunk_bytes of complex values (a whole t node when it
    fits), so memory stays bounded at any N; the Hessian's assembly holds about five times one chunk. The chunks are
    cached only when all of them fit under cache_bytes (UB's b)."""

    def __init__(self, B, rule=None, cache_bytes=2e9, chunk_bytes=2 ** 26):
        self.B = B
        self.rule = quadrature.HopfRule(B.N) if rule is None else rule
        self.w = [self.rule.node_weight(g) for g in range(self.rule.n_t)]
        self.e = B.eig
        row = self.rule.M * B.r * B.m * 16                      # one alpha row at one t node
        self.rows = int(min(self.rule.M, max(1, chunk_bytes // row)))
        self.cached = self.rule.n_t * self.rule.M * row <= cache_bytes
        self._Phi = [self._eval(*b) for b in self._blocks()] if self.cached else None

    def _blocks(self):
        for g in range(self.rule.n_t):
            for u0 in range(0, self.rule.M, self.rows):
                yield g, u0, min(u0 + self.rows, self.rule.M)

    def _eval(self, g, u0, u1):
        rows = None if (u0, u1) == (0, self.rule.M) else (u0, u1)
        return self.B.evaluate_at_t_node(self.rule, g, rows=rows).reshape(-1, self.B.r, self.B.m)

    def chunks(self):
        for i, (g, u0, u1) in enumerate(self._blocks()):
            yield (self._Phi[i] if self.cached else self._eval(g, u0, u1)), self.w[g]

    @property
    def Phi(self):                       # D2-D5 compatibility, small N only
        return [P for P, _ in self.chunks()]

    def energy(self, c, lam):
        q = 0.0
        for P, w in self.chunks():
            s = np.sum(np.abs(P @ c) ** 2, axis=-1)
            q += w * np.sum(s ** 2)
        return 0.5 * np.sum((self.e - lam) * np.abs(c) ** 2) + 0.25 * q

    def cubic(self, c):
        """The Galerkin projection of |psi|^2 psi."""
        g = np.zeros(self.B.m, dtype=complex)
        for P, w in self.chunks():
            psi = P @ c
            s = np.sum(np.abs(psi) ** 2, axis=-1)
            g = g + w * (P.reshape(-1, self.B.m).conj().T @ (s[:, None] * psi).reshape(-1))
        return g

    def grad(self, c, lam):
        devtools.refuse_in_seedcheck('Functional.grad')
        return (self.e - lam) * c + self.cubic(c)

    def hess_apply(self, c, lam, d):
        devtools.refuse_in_seedcheck('Functional.hess_apply')
        out = (self.e - lam) * d
        for P, w in self.chunks():
            psi, dpsi = P @ c, P @ d
            s = np.sum(np.abs(psi) ** 2, axis=-1)
            re = np.real(np.sum(psi.conj() * dpsi, axis=-1))
            v = s[:, None] * dpsi + 2 * re[:, None] * psi
            out = out + w * (P.reshape(-1, self.B.m).conj().T @ v.reshape(-1))
        return out

    def hess_parts(self, c, lam):
        """The real 2m x 2m Hessian's two parts: the diagonal (-Laplacian - lam), and the quartic's, by Gram matrices."""
        devtools.refuse_in_seedcheck('Functional.hess_parts')
        m = self.B.m
        Dq = np.diag(np.concatenate([self.e - lam, self.e - lam]))
        H4 = np.zeros((2 * m, 2 * m))
        for P, w in self.chunks():
            psi = P @ c
            s = np.sum(np.abs(psi) ** 2, axis=-1)
            PR = np.concatenate([np.concatenate([P.real, -P.imag], axis=2),
                                 np.concatenate([P.imag, P.real], axis=2)], axis=1)
            pR = np.concatenate([psi.real, psi.imag], axis=1)
            A = (np.sqrt(w * s)[:, None, None] * PR).reshape(-1, 2 * m)
            v = np.einsum('pa,pab->pb', pR, PR) * np.sqrt(2 * w)
            H4 = H4 + A.T @ A + v.T @ v
        return Dq, H4

    def hess_dense(self, c, lam):
        devtools.refuse_in_seedcheck('Functional.hess_dense')
        Dq, H4 = self.hess_parts(c, lam)
        return Dq + H4


def right_generators(B):
    """The three complex m x m generators of right translation: d pi_n(G_a) on each (n, i) block."""
    out = []
    for G in su2.GENS:
        T = np.zeros((B.m, B.m), dtype=complex)
        col = 0
        for n in B.levels:
            d = su2.gen_matrix(n, G)
            for _ in B.A[n]:
                T[col:col + n + 1, col:col + n + 1] = d
                col += n + 1
        out.append(T)
    return out


def right_rotation(B, U):
    """The complex m x m matrix of right translation by U in SU(2)."""
    R = np.zeros((B.m, B.m), dtype=complex)
    col = 0
    for n in B.levels:
        P = su2.pi(n, U)
        for _ in B.A[n]:
            R[col:col + n + 1, col:col + n + 1] = P
            col += n + 1
    return R


def fibre_structure_matrix(Fn):
    """C (C conj(rho) = rho C) and K, the matrix of psi -> C conj(psi) in the basis, through the rule."""
    B = Fn.B
    r = B.r
    rows = []
    for g in B.gens:
        R = group2i.rep(B.slot, B.E[g])
        rows.append(np.kron(np.eye(r), R) - np.kron(R.conj().T, np.eye(r)))
    _, _, Vh = np.linalg.svd(np.vstack(rows))
    C = Vh[-1].conj().reshape((r, r)).T
    C = C / np.sqrt(np.abs(np.trace(C @ C.conj().T)) / r)
    K = np.zeros((B.m, B.m), dtype=complex)
    for P, w in Fn.chunks():
        CP = np.einsum('ij,pjm->pim', C, P.conj())
        K = K + w * (P.reshape(-1, B.m).conj().T @ CP.reshape(-1, B.m))
    return C, K
