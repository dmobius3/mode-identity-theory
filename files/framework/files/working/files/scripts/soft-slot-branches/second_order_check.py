def r2_point():
    uw, G, M, crit, Q, nrm = gc.point_data({1: 1, 5: 1})
    K = gc.orbit_tangent(uw)
    KM = sp.Matrix.hstack(*M.nullspace())
    K3 = KM * sp.Matrix.hstack(*(K.T * G * KM).nullspace())
    return uw, G, M, crit, Q, nrm, K, KM, K3


def to_orth(j2, x):
    wt = [bc.weight(j2, m) for m in bc.ms(j2)]
    n = j2 + 1
    return [canon(sqrt(wt[a]) * (x[a] + I * x[n + a])) for a in range(n)]


def group_at_u2():
    rs = lambda Mx: Mx.applyfunc(sp.radsimp)
    h1b = rs(gc.rot_z(sp.pi / 2) * gc.Pq(-sqrt(2) / 2, -sqrt(2) / 2, 0, 0))
    h3 = rs(gc.quarter_turn_x() * gc.Pq(-sqrt(2) / 2, 0, 0, sqrt(2) / 2))
    grp, frontier, seen = [sp.eye(16)], [sp.eye(16)], {tuple(sp.eye(16))}
    while frontier:
        nxt = []
        for g in frontier:
            for h in (h1b, h3):
                p = rs(h * g)
                if tuple(p) not in seen:
                    seen.add(tuple(p))
                    grp.append(p)
                    nxt.append(p)
        frontier = nxt
    return grp


def claim_d(dihedral_only=False, out=None):
    rs = lambda Mx: Mx.applyfunc(sp.radsimp)
    J0 = bc.J0(7)
    grp = group_at_u2()
    u2, G, M2, crit2, _, _ = gc.point_data({1: 1, 5: -1})
    K = gc.orbit_tangent(u2)
    KM = sp.Matrix.hstack(*M2.nullspace())
    K3 = KM * sp.Matrix.hstack(*(K.T * G * KM).nullspace())
    Gk = K3.T * G * K3
    comm = [g for g in grp if rs(g * J0 - J0 * g) == sp.zeros(16)]
    anti = [g for g in grp if rs(g * J0 + J0 * g) == sp.zeros(16)]
    use = comm + anti if dihedral_only else grp
    chis, inv = [], True
    for g in use:
        A = rs(Gk.inv() * K3.T * G * g * K3)
        inv &= rs(K3 * A - g * K3) == sp.zeros(16, 3)
        chis.append(sp.radsimp(A.trace()))
    ip = sp.radsimp(sum(c ** 2 for c in chis) / len(use))
    uw, G, M, crit, Q, nrm, Ku, KMu, K3u = r2_point()
    sig = rs(KMu.T * G * J0 * KMu)
    rad = [KMu * r for r in sig.nullspace()]
    Pk3 = K3u * (K3u.T * G * K3u).inv() * K3u.T * G
    outside = sp.Matrix.hstack(*[rs(Pk3 * v) for v in rad]).rank()
    lp = [v for v in rad if rs(Pk3 * v) != sp.zeros(16, 1)][0]
    sol = sp.Matrix.vstack(M, KMu.T * G).gauss_jordan_solve(sp.Matrix.vstack(-G * J0 * lp, sp.zeros(9, 1)))[0]
    p = sol.subs({s_: 0 for s_ in sol.free_symbols})
    partner_ok = rs(J0 * G.inv() * M * p - lp) == sp.zeros(16, 1)
    energy = sp.radsimp((p.T * M * p)[0])
    if out is not None:
        out.update(order=len(grp), dimK3=K3.shape[1], ip=ip, comm=len(comm), anti=len(anti), rank=sig.rank(),
                   radical=len(rad), outside=outside, energy_positive=energy > 0)
    return (len(grp) == 24 and crit2 and K3.shape[1] == 3 and inv and ip == 1 and len(comm) == 4 and len(anti) == 4
            and sig.rank() == 6 and len(rad) == 3 and outside == 1 and partner_ok and energy > 0)


