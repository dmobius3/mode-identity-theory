def canon(z):
    """Exact canonical form: expand, rationalize, expand. Never numeric."""
    return sp.expand(sp.radsimp(sp.expand(sp.sympify(z))))


@functools.lru_cache(maxsize=None)
def cg(j1, j2, j3, m1, m2, m3):
    return clebsch_gordan(j1, j2, j3, m1, m2, m3)


def ms(j):
    return [j - k for k in range(int(2 * j) + 1)]


@functools.lru_cache(maxsize=None)
def T6(j, q):
    """The HS-orthonormal spin-6 operator on V_j: (T_q)_{m m'} = (-1)^{j-m'} <j m; j -m' | 6 q>."""
    out = {}
    for m in ms(j):
        mp_ = m - q
        if abs(mp_) <= j:
            c = (-1) ** int(j - mp_) * cg(j, j, 6, m, -mp_, q)
            if c != 0:
                out[(m, mp_)] = c
    return tuple(sorted(out.items()))


def kappa(j, J):
    T0 = dict(T6(j, 0))
    num = sum(cg(6, j, J, 0, m, m) ** 2 * T0.get((m, m), 0) for m in ms(j))
    den = sum(T0.get((m, m), 0) ** 3 for m in ms(j))
    return canon(num / den)


def tJ(j, s, J, cubic=True):
    P6 = (2 * j + 1) * s * (1 - s)
    return canon(P6 * (s * (2 * J + 1) / 13 + (kappa(j, J) if cubic else 0) * (1 - 2 * s)))


def levels(j):
    return [abs(6 - j) + k for k in range(int(6 + j - abs(6 - j)) + 1)]


def Ypair(j, a, b):
    idx = {m: k for k, m in enumerate(ms(j))}
    return [sp.expand(sum(c * a[idx[m]] * sp.conjugate(b[idx[mp_]]) for (m, mp_), c in T6(j, q)))
            for q in range(-6, 7)]


def couple(j, J, Y, y):
    out = []
    for M in [J - k for k in range(int(2 * J) + 1)]:
        tot = 0
        for qi, q in enumerate(range(-6, 7)):
            m = M - q
            if abs(m) <= j and (m - j) == int(m - j):
                c = cg(6, j, J, q, m, M)
                if c != 0:
                    tot += c * Y[qi] * y[ms(j).index(m)]
        out.append(sp.expand(tot))
    return out


def rinner(a, b):
    return canon(sp.re(sum(sp.conjugate(x) * y for x, y in zip(a, b))))


def F_value(j, J, y):
    v = couple(j, J, Ypair(j, y, y), y)
    return rinner(v, v)


def F_jets(j, J, u, k):
    """F_J(u + t k) = F0 + F1 t + F2 t^2 + ...: returns (F0, F1, 2 F2)."""
    Yu, Yk = Ypair(j, u, u), Ypair(j, k, k)
    Y1 = [p + q for p, q in zip(Ypair(j, u, k), Ypair(j, k, u))]
    l0 = couple(j, J, Yu, u)
    l1 = [x + y for x, y in zip(couple(j, J, Yu, k), couple(j, J, Y1, u))]
    l2 = [x + y for x, y in zip(couple(j, J, Y1, k), couple(j, J, Yk, u))]
    return rinner(l0, l0), 2 * rinner(l0, l1), 2 * (rinner(l1, l1) + 2 * rinner(l0, l2))


def hess_on(j, J, u, ks):
    """The Hessian of F_J at u on span(ks) (real bilinear form), F_J(u), and the gradient along each k."""
    n = len(ks)
    jets = [F_jets(j, J, u, k) for k in ks]
    H = sp.zeros(n)
    for a in range(n):
        H[a, a] = jets[a][2]
    for a in range(n):
        for b in range(a + 1, n):
            hab = F_jets(j, J, u, [x + y for x, y in zip(ks[a], ks[b])])[2]
            H[a, b] = H[b, a] = canon((hab - H[a, a] - H[b, b]) / 2)
    return H, jets[0][0], [jt[1] for jt in jets]


