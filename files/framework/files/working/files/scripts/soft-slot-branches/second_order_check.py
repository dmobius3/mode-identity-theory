def classes():
    """The nine classes of 2I: (size, cos theta) for SU(2) eigenvalues exp(+-i theta)."""
    c5 = [(1 + SQ5) / 4, (SQ5 - 1) / 4, (1 - SQ5) / 4, -(1 + SQ5) / 4]   # theta = pi/5, 2pi/5, 3pi/5, 4pi/5
    return [(1, 1), (1, -1), (30, 0), (20, R(1, 2)), (20, R(-1, 2))] + [(12, c) for c in c5]


def chi_spin(J, c):
    return canon(sp.chebyshevu(int(2 * J), c))


def galois(z):
    return canon(sp.sympify(z).subs(SQ5, -SQ5))


CHI = {"2'": lambda c: galois(2 * c), '2': lambda c: canon(2 * c),
       "3'": lambda c: galois(4 * c ** 2 - 1),
       '4': lambda c: 4 if c in (1, -1) else (0 if c == 0 else (1 if c in (R(1, 2), R(-1, 2)) else -1))}


def mult(J, chi):
    return canon(sum(sz * chi_spin(J, c) * chi(c) for sz, c in classes()) / 120)


