def claim_c(cubic=True, out=None):
    j = R(3)

    def ray(d):
        y = [0] * 7
        for m, c in d.items():
            y[ms(j).index(m)] = c
        nr = sqrt(sum(abs(c) ** 2 for c in y))
        return [canon(c / nr) for c in y]
    rays = {'v3': ray({3: 1}), 'v0': ray({0: 1}), 'oct': ray({2: 1, -2: 1}), 'hex': ray({3: 1, -3: 1})}
    ok, count, bad, bad4 = True, 0, 0, 0
