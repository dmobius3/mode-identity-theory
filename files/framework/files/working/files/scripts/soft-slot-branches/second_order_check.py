    j2, n = 6, 7
    MS = bc.ms(j2)
    a = bc.analyse(6, bc.Q4, bc.vec(6, {2: 1}), False)
    M, G = a['M'], a['G']
    J0 = bc.J0(6)
    gen = bc.to_real(sp.diag(*[I * (phase - m) for m in MS]))           # d/dtheta of R_z(theta) e^{i phase theta}
    uw = sp.Matrix(bc.vec(6, {2: 1}))
    fixes = rs(gen * uw) == sp.zeros(14, 1)
    Cy = sp.zeros(n)
    for a_, m in enumerate(MS):
        Cy[MS.index(-m), a_] = (-1) ** int(3 - m)
    anti = bc.to_real(Cy) * bc.theta(6)                               # the half-turn about y with charge conjugation
    anti_fixes = rs(anti * uw) == uw and rs(anti * J0 + J0 * anti) == sp.zeros(14)
    weights = [phase - m for m in MS]
    w4 = [MS.index(m) for m in MS if abs(phase - m) == 4]
    K = sp.Matrix.hstack(*[(g * uw) for g in [J0] + bc.gens(6)])
    KM = sp.Matrix.hstack(*M.nullspace())
    Kx = KM * sp.Matrix.hstack(*(K.T * G * KM).nullspace())
    sector = sp.Matrix.hstack(*[sp.Matrix(bc.vec(6, {i: c})) for i in w4 for c in (1, I)]) if w4 else sp.zeros(14, 0)
    kernel_is_sector = Kx.shape[1] == 2 and sector.shape[1] == 2 and sp.Matrix.hstack(Kx, sector).rank() == 2
    commutes = rs(gen * M - M * gen) == sp.zeros(14) and rs(gen * J0 - J0 * gen) == sp.zeros(14)
    keep = [i for i in range(14) if i not in w4 + [n + i_ for i_ in w4]]
    S = a['S']
    Sc = S.extract(keep, keep)
    P, z = bc.strip_zero(bc.charpoly(Sc, bc.MU))
    Pn = sp.Poly(sp.expand(P.as_expr()).subs(bc.MU, sp.sqrt(bc.NU)), bc.NU)
    Pu = sp.Poly(sp.expand(Pn.as_expr().subs(bc.NU, bc.NU * a['nrm'] ** 2)), bc.NU).monic()
    simple_neg = bc.count(Pn, None, 0) == Pn.degree() == 4 and sp.gcd(Pn, Pn.diff(bc.NU)).degree() == 0 and \
        Pu == a['Pu']
    j = R(3)
    u = [0] * 7
    u[ms(j).index(1)] = 1
    e3 = [0] * 7
    e3[ms(j).index(-3)] = 1
    ks = [e3, [I * x for x in e3]]
    rr = rinner(Ypair(j, u, u), Ypair(j, u, u))
    gammas, props = {}, True
    for name in ('R4', 'R5'):
        _, s, K_ = SLOTS[name]
        Q = canon(1 + (2 * j + 1) * (1 - s) * rr / (13 * s))
        tot = 0
        for J in levels(j):
            t = tJ(j, s, J)
            if int(2 * J) == K_ or t == 0:
                continue
            H, F0, grads = hess_on(j, J, u, ks)
            Gm = sp.Matrix(2, 2, lambda x, y: rinner(ks[x], ks[y]))
            HS = (H - 6 * F0 * Gm).applyfunc(canon)
            h = canon(HS[0, 0] / Gm[0, 0])
            props &= (HS - h * Gm).applyfunc(canon) == sp.zeros(2) and all(g == 0 for g in grads)
            tot += -t * h / ((2 * J + 1) * s ** 3 * int(2 * J * (2 * J + 2) - K_ * (K_ + 2)))
        gammas[name] = canon(tot / Q ** 2)
    mp.mp.dps = 50
    model_ok = True
    for name in ('R4', 'R5'):
        _, s, K_ = SLOTS[name]
        um = [mp.mpc(0)] * 7
        um[ms(j).index(1)] = mp.mpc(1)
        Hh, Qm, HR, Ru, J0m = mp_hessians(j, s, mp.mpf(sp.N(bc.BETA[name], 60)), K_, um)
        for sign in (1, -1):
            prs, zeros = pairs(J0m, model_hessian(Hh, Qm, HR, Ru, '1e-5', sign))
            w4p = prs[0]
            model_ok &= zeros == 4 and len(prs) == 5 and abs(w4p[1]) < mp.mpf('1e-40') * w4p[0] and \
                abs(w4p[0] / mp.mpf('1e-5') - abs(mp.mpf(sp.N(gammas[name], 50)))) < mp.mpf('1e-6') and \
                (w4p[2] > 0) == (sign * gammas[name] > 0)
    if out is not None:
        out.update(fixes=fixes, anti_fixes=anti_fixes, weights=weights, kernel_is_sector=kernel_is_sector, commutes=commutes, zeros_off=z,
                   P=sp.factor(Pu.as_expr()), same_as_row=Pu == a['Pu'], gammas=gammas, model_ok=model_ok,
                   weight_v1=phase - 1)
    return (fixes and anti_fixes and kernel_is_sector and commutes and z == 4 and simple_neg and props and model_ok and
            gammas == V1_GAMMA)


