def mp_setup(j):
    n = int(2 * j) + 1
    Tq = {q: [(k, mp.mpf(sp.N(v, 60))) for k, v in T6(j, q)] for q in range(-6, 7)}
    return n, ms(j), Tq


def mp_Y(ctx, a, b):
    n, M_, Tq = ctx
    idx = {m: k for k, m in enumerate(M_)}
    return [sum(c * a[idx[m]] * mp.conj(b[idx[mp_]]) for (m, mp_), c in Tq[q]) for q in range(-6, 7)]


def mp_table(j, J):
    tab = []
    for M in [J - k for k in range(int(2 * J) + 1)]:
        row = []
        for qi, q in enumerate(range(-6, 7)):
            m = M - q
            if abs(m) <= j and (m - j) == int(m - j):
                c = cg(6, j, J, q, m, M)
                if c != 0:
                    row.append((qi, ms(j).index(m), mp.mpf(sp.N(c, 60))))
        tab.append(row)
    return tab


def mp_couple(tab, Y, y):
    return [sum(c * Y[qi] * y[mi] for qi, mi, c in row) for row in tab]


def mp_rin(a, b):
    return mp.re(sum(mp.conj(x) * y for x, y in zip(a, b)))


def mp_basis(n):
    out = []
    for a in range(n):
        e = [mp.mpc(0)] * n
        e[a] = mp.mpc(1)
        out.append(e)
    for a in range(n):
        e = [mp.mpc(0)] * n
        e[a] = mp.mpc(0, 1)
        out.append(e)
    return out


def mp_hessians(j, s, beta, K, u):
    """Real Hessians at u of h = |y|^4 + beta ||Y6||^2 and of R~ = -sum t_J F_J / ((2J+1) s^3 mu_J); h(u), R~(u)."""
    ctx = mp_setup(j)
    n = ctx[0]
    N, B = 2 * n, mp_basis(n)
    Yu = mp_Y(ctx, u, u)
    Y1 = [[x + y for x, y in zip(mp_Y(ctx, u, e), mp_Y(ctx, e, u))] for e in B]
    Ys = [[None] * N for _ in range(N)]
    for a in range(N):
        for b in range(a, N):
            Ys[a][b] = [x + y for x, y in zip(mp_Y(ctx, B[a], B[b]), mp_Y(ctx, B[b], B[a]))]
    nu2 = mp_rin(u, u)
    Hh = mp.zeros(N)
    for a in range(N):
        for b in range(a, N):
            Hh[a, b] = Hh[b, a] = 4 * nu2 * mp_rin(B[a], B[b]) + 8 * mp_rin(u, B[a]) * mp_rin(u, B[b]) + \
                beta * 2 * (mp_rin(Y1[a], Y1[b]) + mp_rin(Yu, Ys[a][b]))
    hu = nu2 ** 2 + beta * mp_rin(Yu, Yu)
    HR, Ru = mp.zeros(N), mp.mpf(0)
    for J in levels(j):
        t = tJ(j, s, J)
        if int(2 * J) == K or t == 0:
            continue
        tab = mp_table(j, J)
        l0 = mp_couple(tab, Yu, u)
        l1 = [[x + y for x, y in zip(mp_couple(tab, Yu, e), mp_couple(tab, Y1[k], u))] for k, e in enumerate(B)]
        HF = mp.zeros(N)
        for a in range(N):
            for b in range(a, N):
                l2 = [(x + y) / 2 + z / 2 for x, y, z in
                      zip(mp_couple(tab, Y1[a], B[b]), mp_couple(tab, Y1[b], B[a]), mp_couple(tab, Ys[a][b], u))]
                HF[a, b] = HF[b, a] = 2 * (mp_rin(l1[a], l1[b]) + 2 * mp_rin(l0, l2))
        w = -mp.mpf(sp.N(t, 60)) / ((2 * J + 1) * mp.mpf(sp.N(s, 60)) ** 3 * (2 * J * (2 * J + 2) - K * (K + 2)))
        HR += w * HF
        Ru += w * mp_rin(l0, l0)
    J0 = mp.zeros(N)
    for a in range(n):
        J0[n + a, a], J0[a, n + a] = 1, -1
    return Hh, hu, HR, Ru, J0


def model_hessian(Hh, Q, HR, Ru, eps, sign):
    eps = mp.mpf(eps)
    rho2 = mp.findroot(lambda x: Q * x - 1 + 3 * eps * sign * Ru * x ** 2, 1 / Q)
    return rho2 * Hh / 2 - 2 * mp.eye(Hh.rows) + eps * sign * rho2 ** 2 * HR


def pairs(J0, Hf):
    """Nonzero eigenvalues mu of J0 Hf (one per pair), with real part and Krein sign; and the count below 1e-20."""
    E, V = mp.eig(J0 * Hf)
    out, zeros = [], 0
    for k in range(Hf.rows):
        z = E[k]
        if abs(z) < mp.mpf('1e-20'):
            zeros += 1
            continue
        if mp.im(z) > 0 or (abs(mp.im(z)) < mp.mpf('1e-40') and mp.re(z) > 0):
            v = V[:, k]
            a = mp.matrix([mp.re(x) for x in v])
            b = mp.matrix([mp.im(x) for x in v])
            q = (a.T * Hf * a)[0] + (b.T * Hf * b)[0]
            out.append((abs(z), mp.re(z), q))
    return sorted(out), zeros


def mp_vec(z):
    return mp.matrix([mp.re(x) for x in z] + [mp.im(x) for x in z])


def mp_null(A, tol):
    U, S, V = mp.svd_r(A, full_matrices=True)
    return [V[k, :].T for k in range(A.cols) if (k >= len(S) or abs(S[k]) < tol)]


def mp_orth(vs):
    out = []
    for v in vs:
        w = v.copy()
        for o in out:
            w -= (o.T * w)[0] * o
        nw = mp.sqrt((w.T * w)[0])
        if nw > mp.mpf('1e-25'):
            out.append(w / nw)
    return out


def effective_4x4(Hh, Q, HR, Ru, J0, u, eps):
    """The non-structural part of the generalized kernel of S0 = J0 H0 at R2's point: Z' = {z in Z : sigma(z, Sigma) = 0},
    Sigma the orbit tangent and the partners of its sigma-radical; the eigenvalues of the 4 x 4 problem there."""
    N = Hh.rows
    H0 = Hh / (2 * Q) - 2 * mp.eye(N)
    sig = lambda a, b: (a.T * J0 * b)[0]
    j = R(7, 2)
    M_ = ms(j)
    Jp, Jz = mp.zeros(8), mp.zeros(8)
    for a, m in enumerate(M_):
        Jz[a, a] = mp.mpf(m)
        if a > 0:
            Jp[a - 1, a] = mp.sqrt(mp.mpf(j * (j + 1) - m * (m + 1)))
    Jx, Jy = (Jp + Jp.T) / 2, (Jp - Jp.T) / (2j)
    um = mp.matrix(u)
    th = [0] * 8
    thi = [0] * 8
    for a, m in enumerate(M_):
        th[M_.index(-m)] = (-1) ** int(j - m) * mp.conj(u[a])
        thi[M_.index(-m)] = (-1) ** int(j - m) * mp.conj(1j * u[a])
    Ku = mp_orth([mp_vec([1j * x for x in u])] + [mp_vec(list(-1j * (Jk * um))) for Jk in (Jx, Jy, Jz)] +
                 [mp_vec(th), mp_vec(thi)])
    kerH = mp_orth(mp_null(H0, mp.mpf('1e-30')))
    S0 = J0 * H0
    U, S, V = mp.svd_r(S0)

    def partner(y):
        x = mp.zeros(N, 1)
        for k in range(len(S)):
            if abs(S[k]) > mp.mpf('1e-30'):
                x += ((U[:, k].T * y)[0] / S[k]) * V[k, :].T
        return x
    SK = mp.matrix([[sig(a, b) for b in Ku] for a in Ku])
    radK = [sum((c[i] * Ku[i] for i in range(6)), mp.zeros(N, 1)) for c in mp_null(SK, mp.mpf('1e-25'))]
    Sigma = Ku + [partner(y) for y in radK]
    SM = mp.matrix([[sig(a, b) for b in kerH] for a in kerH])
    radM = [sum((c[i] * kerH[i] for i in range(9)), mp.zeros(N, 1)) for c in mp_null(SM, mp.mpf('1e-25'))]

    def off_K(v):
        w = v.copy()
        for o in Ku:
            w -= (o.T * w)[0] * o
        return w
    lp = [r for r in radM if mp.norm(off_K(r)) > mp.mpf('1e-20')][0]
    Zb = mp_orth(kerH + [partner(y) for y in radK] + [partner(lp)])
    C = mp.matrix([[sig(s_, z) for z in Zb] for s_ in Sigma])
    Zp = mp_orth([sum((c[i] * Zb[i] for i in range(len(Zb))), mp.zeros(N, 1)) for c in mp_null(C, mp.mpf('1e-25'))])
    Hf = model_hessian(Hh, Q, HR, Ru, eps, 1)
    Hb = mp.matrix([[(a.T * Hf * b)[0] for b in Zp] for a in Zp])
    Sb = mp.matrix([[sig(a, b) for b in Zp] for a in Zp])
    ev = mp.eig(-Sb ** -1 * Hb, left=False, right=False)
    return len(Zb), len(Zp), sorted(abs(z) for z in ev), max(abs(mp.re(z)) for z in ev)


def claim_f(sign=1, out=None):
    mp.mp.dps = 50
    j, s, K = SLOTS['R2']
    u = [mp.mpc(0)] * 8
    u[ms(j).index(R(5, 2))] = mp.sqrt(3) / 2
    u[ms(j).index(R(-3, 2))] = mp.mpf(1) / 2
    Hh, Q, HR, Ru, J0 = mp_hessians(j, s, mp.mpf(24) / 13, K, u)
    s_vals = sorted([mp.sqrt(mp.mpf(87616) / 20449), mp.sqrt(mp.mpf(204544) / 20449)])
    ok, rows, small = True, [], {}
    for eps in ('1e-3', '1e-5'):
        prs, zeros = pairs(J0, model_hessian(Hh, Q, HR, Ru, eps, sign))
        rows.append((eps, zeros, prs))
        ok &= zeros == 8 and len(prs) == 4
        if len(prs) == 4:
            ok &= all(abs(r) < mp.mpf('1e-40') * a and q > 0 for a, r, q in prs)
            ok &= all(abs(prs[2 + k][0] - s_vals[k] / (2 * Q)) < mp.mpf('1e-2') * s_vals[k] for k in range(2))
            small[eps] = (prs[0][0], prs[1][0])
    if ok:
        r_eps = small['1e-3'][0] / small['1e-5'][0]
        r_half = small['1e-3'][1] / small['1e-5'][1]
        ok &= abs(r_eps - 100) < 1e-2 and abs(r_half - 10) < 1e-2
    if out is not None:
        out['rows'] = rows
    if ok and sign == 1:
        dZ, dZp, ev, mre = effective_4x4(Hh, Q, HR, Ru, J0, u, '1e-5')
        full = sorted([small['1e-5'][0]] * 2 + [small['1e-5'][1]] * 2)
