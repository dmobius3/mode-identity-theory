def claim_e(shift=True, out=None):
    j, s, K = SLOTS['R2']
    uw, G, M, crit, Q, nrm, Ku, KM, K3 = r2_point()
    u = [canon(z / sqrt(nrm)) for z in to_orth(7, list(uw))]
    ks = [to_orth(7, list(K3[:, c])) for c in range(3)]
    Gm = sp.Matrix(3, 3, lambda a, b: rinner(ks[a], ks[b]))
    ok = rinner(u, u) == 1 and all(rinner(u, k) == 0 for k in ks)
    HS_tot, R_u, rows = 0, 0, []
    for J in levels(j):
        t = tJ(j, s, J)
        if int(2 * J) == K or t == 0:
            continue
        H, F0, grads = hess_on(j, J, u, ks)
        HS = (H - (6 * F0 * Gm if shift else sp.zeros(3))).applyfunc(canon)
        h = canon(HS[0, 0] / Gm[0, 0])
        prop = (HS - h * Gm).applyfunc(canon) == sp.zeros(3)
        mu = int(2 * J * (2 * J + 2) - K * (K + 2))
        HS_tot += -t * h / ((2 * J + 1) * s ** 3 * mu)
        R_u += -t * F0 / ((2 * J + 1) * s ** 3 * mu)
        ok &= prop and all(g == 0 for g in grads) and (h == R2_H[J] if shift else True)
        rows.append((J, t, F0, h, prop))
    gamma = canon(HS_tot / Q ** 2)
    if out is not None:
        out.update(rows=rows, R_u=canon(R_u), HS=canon(HS_tot), gamma=gamma)
    return ok and gamma == GAMMA and canon(R_u) == R(-27273813, 37780754440) and canon(HS_tot) == R(805140, 112285459)


