#!/usr/bin/env python3
"""The germ at R2's degenerate point, the interior critical point of the cyclic line {5/2, -3/2} at level 7, in
exact arithmetic over Q(sqrt 2, i), with branches_check.py's machinery (the quartic, the metric, the generators and
Theta), imported and not changed.

  A  the point u = sqrt(3/4) v_{5/2} + sqrt(1/4) v_{-3/2} (weighted coordinates {1: 1, 5: 1}) is critical, with
     Q = 161/143, orbit dimension k = 6 = dim Gamma, and signature (0, 3, 6) of M_u on N_u: degenerate, so Lemma G
     does not apply, and the isotropy group Gamma_u is finite
  B  two elements of Gamma_u, exactly: the quarter-turn about z with the fibre phase e^{5 pi i/4}, and the half-turn
     about y with the fibre element -j
  C  in the frame turned by pi/4 about z, where u becomes u'' = sqrt(3/4) v_{5/2} - sqrt(1/4) v_{-3/2} up to a fibre
     phase, the quarter-turn about x with the fibre element (-1 + k)/sqrt 2 fixes u''; with the quarter-turn about z
     it generates the octahedral group, so the rotation part of Gamma_u is O (no finite subgroup of SO(3) properly
     contains O)
  D  the fixed space of Gamma_u in E0 is the real line through the point, computed from the two quarter-turns in
     that frame: the slice of Lemma G′ is a point, and the germ is pinned by the symmetry
  E  the cross-check on the dihedral subgroup generated by B's two elements: its fixed space in E0 is the real plane
     of the coefficients of v_{5/2} and v_{-3/2}; no infinitesimal symmetry preserves it; its slice direction lies
     in N_u; M_u is nondegenerate on it, with tau^T M tau / tau^T G tau = 168/143 for unit u; and the
     nine-dimensional kernel of M_u meets it only in 0
Mutation arms, each of which must turn its claim red for its own reason: the quarter-turn about x in u's own frame
(it moves u's quaternionic line); the fibre element of C with k replaced by -k; D's fixed space from the quarter-turn
about z alone (dimension 4, not 1); E without the half-turn (the rotation about z, with a phase, preserves the plane);
the line point with p_{-3/2} = 2 p_{5/2} (not critical). The exit status is 1 if any claim fails or any arm stays
green. Runs in about ten seconds.
"""
import sys
from pathlib import Path

import sympy as sp
from sympy import I, Rational as R, sqrt

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import branches_check as bc  # noqa: E402

J2, N2, N = 7, 16, 8
JJ = R(7, 2)
MS = bc.ms(J2)


def Pq(a, b, c, d):
    """The fibre element a + b i + c j + d k, acting on the right, as a real matrix: i is J0 and j is Theta."""
    J0, T = bc.J0(J2), bc.theta(J2)
    return a * sp.eye(N2) + b * J0 + c * T + d * T * J0


def point_data(rep):
    hp, grad, hess = bc.setup(J2, bc.Q2)
    G = bc.metric(J2)
    u = sp.Matrix(bc.vec(J2, rep))
    sub = dict(zip(hp.gens, list(u)))
    nrm = (u.T * G * u)[0]
    hv = sp.expand(hp.as_expr().subs(sub))
    lam = 4 * hv / nrm
    gv = sp.Matrix([sp.expand(g.as_expr().subs(sub)) for g in grad])
    crit = (gv - lam * G * u).applyfunc(sp.simplify) == sp.zeros(N2, 1)
    M = sp.Matrix(N2, N2, lambda i, k: sp.expand(hess[i][k].as_expr().subs(sub))) - lam * G
    return u, G, M, crit, hv / nrm**2, nrm


def orbit_tangent(u):
    J0, T = bc.J0(J2), bc.theta(J2)
    return sp.Matrix.hstack(*([J0 * u] + [g * u for g in bc.gens(J2)] + [T * u, T * J0 * u]))


def rot_z(phi):
    return bc.to_real(sp.diag(*[sp.exp(-I * m * phi) for m in MS])).applyfunc(sp.radsimp)


def half_turn_y():
    C = sp.zeros(N)
    for a, m in enumerate(MS):
        C[MS.index(-m), a] = (-1) ** int(JJ - m)
    return bc.to_real(C)


def quarter_turn_x():
    """D(R_x(pi/2)) in weighted coordinates: i^{m'-m} d^j_{m'm}(pi/2), from the closed form for d."""
    def dsmall(mp_, m):
        s = 0
        for k in range(0, 9):
            a1, a2, a3, a4 = JJ + m - k, k, JJ - k - mp_, k - m + mp_
            if min(a1, a2, a3, a4) < 0:
                continue
            num = sqrt(sp.factorial(JJ + mp_) * sp.factorial(JJ - mp_) * sp.factorial(JJ + m) * sp.factorial(JJ - m))
            s += (-1) ** int(k - m + mp_) * num / (sp.factorial(a1) * sp.factorial(a2) * sp.factorial(a3)
                                                    * sp.factorial(a4)) * (sqrt(2) / 2) ** int(2 * JJ)
        return sp.radsimp(s)
    D = sp.Matrix(N, N, lambda a, b: I ** int(MS[a] - MS[b]) * dsmall(MS[a], MS[b]))
    W = sp.diag(*[sqrt(bc.weight(J2, m)) for m in MS])
    return bc.to_real((W.inv() * D * W).applyfunc(sp.radsimp)).applyfunc(sp.radsimp)


def is_rotation(D, conj):
    """D is orthogonal for the metric, and conjugates the generators as the rotation it stands for."""
    G = bc.metric(J2)
    gens = bc.gens(J2)
    ok = (D.T * G * D - G).applyfunc(sp.radsimp) == sp.zeros(N2)
    for X, Y in conj:
        ok &= (D * gens[X] - Y(gens) * D).applyfunc(sp.radsimp) == sp.zeros(N2)
    return ok


def fixed_space(elements):
    A = sp.Matrix.vstack(*[(h - sp.eye(N2)) for h in elements]).applyfunc(sp.radsimp)
    return A.nullspace(simplify=True)


def keeps_line(D, u):
    J0, T = bc.J0(J2), bc.theta(J2)
    line = sp.Matrix.hstack(u, J0 * u, T * u, T * J0 * u)
    return sp.Matrix.hstack(line, (D * u).applyfunc(sp.radsimp)).rank(simplify=True) == 4


def main():
    failed, arms = 0, []
    J0 = bc.J0(J2)

    # A
    u, G, M, crit, Q, nrm = point_data({1: 1, 5: 1})
    K = orbit_tangent(u)
    k = K.rank()
    Nb = sp.Matrix.hstack(u, K).T.multiply(G).nullspace()
    NM = sp.Matrix.hstack(*Nb)
    MN = NM.T * M * NM
    n0 = len(MN.nullspace())
    ev = [e for e in sp.Poly(MN.charpoly(sp.Symbol('x')).as_expr(), sp.Symbol('x')).all_roots()]
    neg, pos = sum(1 for e in ev if e < 0), sum(1 for e in ev if e > 0)
    okA = crit and Q == R(161, 143) and k == 6 and (neg, n0, pos) == (0, 3, 6)
    failed += not okA
    print('A  the point sqrt(3/4) v_{5/2} + sqrt(1/4) v_{-3/2}: critical %s, Q = %s, k = %d, (n-, n0, n+) = (%d, %d, %d)'
          % (crit, Q, k, neg, n0, pos))
    print('   degenerate (n0 > 0), so Lemma G does not apply; k = dim Gamma = 6, so Gamma_u is finite: %s'
          % ('PASS' if okA else 'FAIL'))

    # B
    gens = bc.gens(J2)
    Dz = rot_z(sp.pi / 2)
    Dy = half_turn_y()
    rz_ok = is_rotation(Dz, [(2, lambda g: g[2]), (0, lambda g: g[1])]) or \
        is_rotation(Dz, [(2, lambda g: g[2]), (0, lambda g: -g[1])])
    ry_ok = is_rotation(Dy, [(1, lambda g: g[1]), (0, lambda g: -g[0]), (2, lambda g: -g[2])])
    h1 = (Dz * Pq(-sqrt(2) / 2, -sqrt(2) / 2, 0, 0)).applyfunc(sp.radsimp)
    h2 = Dy * Pq(0, 0, -1, 0)
    okB = rz_ok and ry_ok and (h1 * u - u).applyfunc(sp.radsimp) == sp.zeros(N2, 1) and h2 * u == u
    failed += not okB
    print('B  the quarter-turn about z with fibre e^{5 pi i/4}, and the half-turn about y with fibre -j, fix u: %s'
          % ('PASS' if okB else 'FAIL'))

    # C
    ratio = sp.simplify(sp.exp(-I * R(3, 8) * sp.pi) / sp.exp(I * R(5, 8) * sp.pi))   # e^{-i m phi}, phi = -pi/4
    u2, _, _, crit2, Q2v, _ = point_data({1: 1, 5: -1})
    Dx = quarter_turn_x()
    rx_ok = is_rotation(Dx, [(0, lambda g: g[0]), (2, lambda g: g[1])]) or \
        is_rotation(Dx, [(0, lambda g: g[0]), (2, lambda g: -g[1])])
    p3 = (-sqrt(2) / 2, 0, 0, sqrt(2) / 2)
    h3 = (Dx * Pq(*p3)).applyfunc(sp.radsimp)
    h1b = rot_z(sp.pi / 2) * Pq(-sqrt(2) / 2, -sqrt(2) / 2, 0, 0)
    h1b = h1b.applyfunc(sp.radsimp)
    fixes = (h3 * u2 - u2).applyfunc(sp.radsimp) == sp.zeros(N2, 1) and \
        (h1b * u2 - u2).applyfunc(sp.radsimp) == sp.zeros(N2, 1)
    okC = ratio == -1 and crit2 and Q2v == Q and rx_ok and sp.radsimp(sum(x**2 for x in p3)) == 1 and fixes
    failed += not okC
    print('C  turned by pi/4 about z, u becomes u\'\' = sqrt(3/4) v_{5/2} - sqrt(1/4) v_{-3/2} up to a phase'
          ' (the two phases differ by %s); u\'\' is critical with the same Q: %s' % (ratio, crit2 and Q2v == Q))
    print('   the quarter-turn about x with fibre (-1 + k)/sqrt 2 fixes u\'\', and so does the one about z: %s'
          % fixes)
    print('   the two quarter-turns generate the octahedral group O, so the rotation part of Gamma_u is O: %s'
          % ('PASS' if okC else 'FAIL'))

    # D
    fx = fixed_space([h1b, h3])
    lineD = len(fx) == 1 and sp.Matrix.hstack(fx[0], u2).rank(simplify=True) == 1
    failed += not lineD
    print('D  the fixed space of Gamma_u in E0 has dimension %d, the real line through the point: %s'
          % (len(fx), 'PASS' if lineD else 'FAIL'))
    print('   so the slice of Lemma G′ is a point and the germ is pinned by the symmetry')

    # E
    F = sp.Matrix.hstack(*fixed_space([h1, h2]))
    P = F * (F.T * G * F).inv() * F.T * G
    pres = sp.Matrix.hstack(*[sp.Matrix.vstack(*[(sp.eye(N2) - P) * g * F[:, c] for c in range(F.shape[1])])
                              for g in [J0] + gens + [bc.theta(J2), bc.theta(J2) * J0]])
    no_sym = pres.rank(simplify=True) == 6
    tau = F * (u.T * G * F).nullspace()[0]
    in_N = (K.T * G * tau) == sp.zeros(6, 1)
    hess_ratio = sp.nsimplify((tau.T * M * tau)[0] / (tau.T * G * tau)[0] / nrm)
    kerM = sp.Matrix.hstack(*M.nullspace())
    meets = sp.Matrix.hstack(kerM, F).rank() - kerM.shape[1] - F.shape[1]
    okE = F.shape[1] == 2 and no_sym and in_N and hess_ratio == R(168, 143) and kerM.shape[1] == 9 and meets == 0
    failed += not okE
    print('E  the dihedral subgroup of B: fixed space of dimension %d; no infinitesimal symmetry preserves it: %s'
          % (F.shape[1], no_sym))
    print('   its slice direction tau = %s, in N_u: %s; tau^T M tau / tau^T G tau = %s for unit u'
          % ([(i, tau[i]) for i in range(N2) if tau[i] != 0], in_N, hess_ratio))
    print('   ker M_u has dimension %d and meets the fixed space only in 0: %s; %s'
          % (kerM.shape[1], meets == 0, 'PASS' if okE else 'FAIL'))

    # arms
    arms.append(("the quarter-turn about x in u's own frame: it moves u's quaternionic line", not keeps_line(Dx, u)))
    h3bad = (Dx * Pq(-sqrt(2) / 2, 0, 0, -sqrt(2) / 2)).applyfunc(sp.radsimp)
    arms.append(("C's fibre element with k replaced by -k: it does not fix u''",
                 (h3bad * u2 - u2).applyfunc(sp.radsimp) != sp.zeros(N2, 1)))
    fz = fixed_space([h1b])
    arms.append(("D from the quarter-turn about z alone: dimension %d, not 1" % len(fz), len(fz) != 1))
    F1 = sp.Matrix.hstack(*fixed_space([h1]))
    P1 = F1 * (F1.T * G * F1).inv() * F1.T * G
    pres1 = sp.Matrix.hstack(*[sp.Matrix.vstack(*[(sp.eye(N2) - P1) * g * F1[:, c] for c in range(F1.shape[1])])
                               for g in [J0] + gens + [bc.theta(J2), bc.theta(J2) * J0]])
    arms.append(("E without the half-turn: a rotation with a phase preserves the plane", pres1.rank(simplify=True) < 6))
    _, _, _, crit_bad, _, _ = point_data({1: 1, 5: 2})
    arms.append(("the line point with p_{-3/2} = 2 p_{5/2}: not critical", not crit_bad))
    for label, red in arms:
        print('   arm: %-78s %s' % (label, 'RED' if red else 'green (FAIL)'))
    print('%d claims failed; %d/%d arms red' % (failed, sum(r for _, r in arms), len(arms)))
    failed += sum(not red for _, red in arms)
    if failed:
        raise SystemExit(1)


if __name__ == '__main__':
    main()
